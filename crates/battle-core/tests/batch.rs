fn close(a: f64, b: f64) {
    assert!((a - b).abs() < 1e-12, "{a} != {b}");
}

#[test]
fn sha256_seed_vectors_match_independent_hashlib_reference() {
    // Independently generated by Python hashlib over the documented bytes.
    assert_eq!(derive_trial_seed(0, 0), 9_752_365_817_500_101_322);
    assert_eq!(derive_trial_seed(42, 0), 929_680_476_152_720_637);
    assert_eq!(derive_trial_seed(42, 1), 3_653_063_786_861_075_378);
    assert_eq!(
        derive_trial_seed(u64::MAX, 999_999),
        8_086_974_361_644_878_516
    );
}

#[test]
fn wilson_has_reference_values_and_preserves_no_observations() {
    assert_eq!(wilson_interval(0, 0).unwrap(), None);
    assert!(wilson_interval(1, 0).is_err());
    assert!(wilson_interval(11, 10).is_err());
    let middle = wilson_interval(50, 100).unwrap().unwrap();
    close(middle.lower, 0.403_831_530_365_995_6);
    close(middle.upper, 0.596_168_469_634_004_4);
    let none = wilson_interval(0, 10).unwrap().unwrap();
    close(none.lower, 0.0);
    close(none.upper, 0.277_532_799_862_889_2);
    let all = wilson_interval(10, 10).unwrap().unwrap();
    close(all.lower, 0.722_467_200_137_110_7);
    close(all.upper, 1.0);
}

#[test]
fn wins_losses_are_actual_engine_outcomes_and_settlement_stays_unknown() {
    for (ally, enemy, wins, losses) in [(1_000.0, 0.0, 4, 0), (0.0, 1_000.0, 0, 4)] {
        let input = validate(scenario(ally, enemy)).unwrap();
        let result = run_batch(
            &input,
            &BatchRequest {
                trials: 4,
                seed: 42,
            },
            &mut || false,
        )
        .unwrap();
        assert_eq!((result.total, result.started, result.completed), (4, 4, 4));
        assert_eq!(
            (result.wins, result.losses, result.draws, result.incomplete),
            (wins, losses, 0, 0)
        );
        assert_eq!(result.probability_denominator, 4);
        assert_eq!(result.run_hp_loss_unknown_count, 4);
        assert!(result
            .ledger
            .iter()
            .all(|trial| trial.run_hp_loss.is_none()));
        let json = serde_json::to_value(&result).unwrap();
        assert!(json["ledger"][0]["run_hp_loss"].is_null());
        assert_eq!(result.scenario_sha256, input.fingerprint());
    }
}

#[test]
fn action_limit_is_incomplete_and_not_a_loss_or_zero_probability() {
    let mut raw = scenario(0.0, 0.0);
    raw.max_actions = 1;
    let input = validate(raw).unwrap();
    let result = run_batch(&input, &BatchRequest { trials: 3, seed: 9 }, &mut || false).unwrap();
    assert_eq!(
        (
            result.started,
            result.completed,
            result.incomplete,
            result.losses
        ),
        (3, 0, 3, 0)
    );
    assert_eq!(result.probability_denominator, 0);
    assert_eq!(result.win_rate, None);
    assert_eq!(result.loss_rate_ci95, None);
    assert!(result
        .ledger
        .iter()
        .all(|trial| trial.termination == Termination::ActionLimit));
}

#[test]
fn incomplete_trials_are_excluded_from_a_mixed_batch_denominator() {
    let mut raw = scenario(60.0, 0.0);
    raw.allies[0].stats.crit_rate = 0.5;
    raw.max_actions = 1;
    let input = validate(raw).unwrap();
    let result = run_batch(
        &input,
        &BatchRequest {
            trials: 64,
            seed: 1234,
        },
        &mut || false,
    )
    .unwrap();
    assert!(result.wins > 0 && result.incomplete > 0);
    assert_eq!(result.started, 64);
    assert_eq!(result.completed, result.wins);
    assert_eq!(result.completed + result.incomplete, result.started);
    assert_eq!(result.probability_denominator, result.wins);
    assert_eq!(result.win_rate, Some(1.0));
    assert_eq!(result.loss_rate, Some(0.0));
    assert_eq!(
        result.win_rate_ci95,
        wilson_interval(u64::from(result.wins), u64::from(result.wins)).unwrap()
    );
}

#[test]
fn explicit_profile_budget_defeat_is_preserved_with_its_reason() {
    let mut raw = scenario(0.0, 0.0);
    raw.max_av = 1.0;
    let input = validate(raw).unwrap();
    let result = run_batch(&input, &BatchRequest { trials: 2, seed: 3 }, &mut || false).unwrap();
    assert_eq!(
        (result.completed, result.losses, result.incomplete),
        (2, 2, 0)
    );
    assert_eq!(result.loss_rate, Some(1.0));
    assert!(result
        .ledger
        .iter()
        .all(|trial| trial.termination == Termination::AvBudgetExhausted));
    assert!(result.ledger.iter().all(|trial| trial.actions == 0));
}

#[test]
fn cancellation_before_start_keeps_all_trials_unstarted() {
    let input = validate(scenario(1_000.0, 0.0)).unwrap();
    let result = run_batch(
        &input,
        &BatchRequest {
            trials: 100,
            seed: 1,
        },
        &mut || true,
    )
    .unwrap();
    assert_eq!(
        (
            result.total,
            result.started,
            result.unstarted,
            result.cancelled
        ),
        (100, 0, 100, 0)
    );
    assert!(result.cancellation_requested);
    assert_eq!(result.win_rate_ci95, None);
    assert_eq!(result.run_hp_loss_unknown_count, 0);
    assert!(result.ledger.is_empty());
}

#[test]
fn cancellation_propagates_into_engine_and_stops_following_trials() {
    let input = validate(scenario(0.0, 0.0)).unwrap();
    let mut polls = 0;
    let result = run_batch(
        &input,
        &BatchRequest {
            trials: 10,
            seed: 1,
        },
        &mut || {
            polls += 1;
            polls >= 3
        },
    )
    .unwrap();
    assert_eq!(
        (
            result.started,
            result.completed,
            result.incomplete,
            result.cancelled,
            result.unstarted
        ),
        (1, 0, 1, 1, 9)
    );
    assert_eq!(result.ledger[0].termination, Termination::Cancelled);
    assert!(result.cancellation_requested);
    assert_eq!(result.loss_rate, None);
}

#[test]
fn trials_replay_by_index_and_interleaved_runs_do_not_leak_state() {
    let mut raw = scenario(60.0, 150.0);
    raw.allies[0].stats.speed = 101.0;
    raw.allies[0].stats.crit_rate = 0.5;
    let input = validate(raw).unwrap();
    let request = BatchRequest {
        trials: 64,
        seed: 1234,
    };
    let first = run_batch(&input, &request, &mut || false).unwrap();
    assert!(first.wins > 0 && first.losses > 0);
    for trial in &first.ledger {
        let single = simulate(&input, trial.seed, false).unwrap();
        assert_eq!(single.outcome, trial.outcome);
        assert_eq!(single.termination, trial.termination);
        assert_eq!(single.actions, trial.actions);
        assert_eq!(single.elapsed_av, trial.elapsed_av);
        assert_eq!(
            trial.seed,
            derive_trial_seed(request.seed, u64::from(trial.index))
        );
    }
    let other = validate(scenario(0.0, 1_000.0)).unwrap();
    run_batch(
        &other,
        &BatchRequest {
            trials: 3,
            seed: 999,
        },
        &mut || false,
    )
    .unwrap();
    let second = run_batch(&input, &request, &mut || false).unwrap();
    assert_eq!(
        serde_json::to_value(first).unwrap(),
        serde_json::to_value(second).unwrap()
    );
}

#[test]
fn invalid_trial_counts_are_rejected_before_cancellation_or_engine_work() {
    let input = validate(scenario(1_000.0, 0.0)).unwrap();
    for trials in [0, 1_000_001] {
        let mut polls = 0;
        let result = run_batch(&input, &BatchRequest { trials, seed: 1 }, &mut || {
            polls += 1;
            false
        });
        assert!(result.is_err());
        assert_eq!(polls, 0);
    }
    let upper_bound = run_batch(
        &input,
        &BatchRequest {
            trials: 1_000_000,
            seed: 1,
        },
        &mut || true,
    )
    .unwrap();
    assert_eq!(upper_bound.unstarted, 1_000_000);
    assert!(
        serde_json::from_str::<BatchRequest>(r#"{"trials":1,"seed":"2","unknown":3}"#).is_err()
    );
}

#[test]
fn json_seeds_are_lossless_decimal_strings_including_u64_max() {
    let request: BatchRequest =
        serde_json::from_str(r#"{"trials":1,"seed":"18446744073709551615"}"#).unwrap();
    assert_eq!(request.seed, u64::MAX);
    assert_eq!(
        serde_json::to_value(&request).unwrap()["seed"],
        u64::MAX.to_string()
    );
    assert!(serde_json::from_str::<BatchRequest>(r#"{"trials":1,"seed":42}"#).is_err());
    assert!(
        serde_json::from_str::<BatchRequest>(r#"{"trials":1,"seed":"18446744073709551616"}"#)
            .is_err()
    );
    let input = validate(scenario(1_000.0, 0.0)).unwrap();
    let result = run_batch(&input, &request, &mut || false).unwrap();
    let serialized = serde_json::to_value(&result).unwrap();
    assert_eq!(serialized["master_seed"], u64::MAX.to_string());
    assert_eq!(
        serialized["ledger"][0]["seed"],
        result.ledger[0].seed.to_string()
    );
    let mut trial = result.ledger[0].clone();
    trial.seed = u64::MAX;
    assert_eq!(
        serde_json::to_value(trial).unwrap()["seed"],
        u64::MAX.to_string()
    );
}
